"""Generate consistent Indonesian neural narration as static web audio.

Run: uv run --with edge-tts --with mutagen python scripts/build-culture-narration.py
Only public culture descriptions are sent to the speech service. The game plays
the resulting MP3 files locally; it does not call a TTS service at runtime.
"""

import asyncio
import hashlib
import json
import subprocess
from pathlib import Path

import edge_tts
from mutagen.mp3 import MP3

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'public/audio/culture'
VOICE = 'id-ID-GadisNeural'
RATE = '+10%'


def narration(entry):
    # Narration reads exactly the descriptions, without headings or added facts.
    return '\n\n'.join(entry['description'])


async def main():
    # Read the authoritative content module through Node, not a fragile JS regex.
    code = """
import {HOUSE_EXHIBITS,CULTURE_GUIDES} from './public/assets/sultra-culture-data.js';
import {getStoryPages} from './public/assets/sultra-story-pages.js';
console.log(JSON.stringify([
  ...HOUSE_EXHIBITS.map(entry => ({...entry, pages: getStoryPages(entry)})),
  ...CULTURE_GUIDES,
]));
"""
    raw = subprocess.check_output(['node', '--input-type=module', '-e', code], cwd=ROOT)
    entries = json.loads(raw.decode('utf-8'))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    metadata_path = OUTPUT / 'narration.json'
    old = json.loads(metadata_path.read_text(encoding='utf-8')) if metadata_path.exists() else {}
    metadata = {}
    limit = asyncio.Semaphore(3)

    async def recording(recording_id, text, previous):
        if not isinstance(text, str) or not text.strip():
            raise ValueError(f'Empty narration for {recording_id}')
        digest = hashlib.sha256((VOICE + RATE + text).encode()).hexdigest()
        path = OUTPUT / f'{recording_id}.mp3'
        if not path.exists() or previous.get('sha256') != digest:
            async with limit:
                temporary = path.with_suffix('.pending.mp3')
                for attempt in range(3):
                    try:
                        await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(temporary))
                        if MP3(temporary).info.length <= .4:
                            raise ValueError('Narration is unexpectedly short')
                        temporary.replace(path)
                        break
                    except Exception:
                        if attempt == 2:
                            raise
                        await asyncio.sleep(2 * (attempt + 1))
        duration = round(MP3(path).info.length, 2)
        if duration <= .4:
            raise ValueError(f'Invalid narration duration for {recording_id}')
        print(f'{recording_id}: {duration}s, {path.stat().st_size} bytes', flush=True)
        return dict(url=f'/audio/culture/{path.name}', voice=VOICE,
                    language='id-ID', rate=RATE, duration=duration,
                    sha256=digest, transcript=text)

    async def generate(entry):
        text = narration(entry)
        previous = old.get(entry['id'], {})
        pages = entry.get('pages', [])
        if pages and ' '.join(' '.join(pages).split()) != ' '.join(text.split()):
            raise ValueError(f"Story pages changed the description for {entry['id']}")
        previous_pages = previous.get('pages', [])
        records = await asyncio.gather(
            recording(entry['id'], text, previous),
            *(recording(f"{entry['id']}-page-{index + 1}", page,
                        previous_pages[index] if index < len(previous_pages) else {})
              for index, page in enumerate(pages)),
        )
        metadata[entry['id']] = records[0]
        if pages:
            metadata[entry['id']]['pages'] = records[1:]

    await asyncio.gather(*(generate(entry) for entry in entries))
    ordered = {entry['id']: metadata[entry['id']] for entry in entries}
    metadata_path.write_text(json.dumps(ordered, ensure_ascii=False, indent=2), encoding='utf-8')
    manifest = {}
    for key, value in ordered.items():
        manifest[key] = {field: value[field] for field in
                         ('url', 'voice', 'language', 'rate', 'duration', 'sha256')}
        if 'pages' in value:
            manifest[key]['pages'] = [dict(text=page['transcript'], **{
                field: page[field] for field in ('url', 'duration', 'sha256')
            }) for page in value['pages']]
    (ROOT / 'public/assets/sultra-narration-manifest.js').write_text(
        '// Generated by scripts/build-culture-narration.py.\nexport default '
        + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    page_count = sum(len(value.get('pages', [])) for value in ordered.values())
    print(f'Generated {len(manifest)} full descriptions and {page_count} story pages in Indonesian at {RATE}.', flush=True)


if __name__ == '__main__':
    asyncio.run(main())
